using System.Text;
using NDMicroAsm.Core;
using NDMicroAsm.ND10;
using NDMicroAsm.ND1X0;
using NDMicroAsm.ND500;
using NDMicroAsm.ND5000;

// ndmicroasm - command-line front end of the Norsk Data micro code assemblers.
//
// One sub-command per CPU generation and direction. Every assembler writes its
// outputs NEXT TO THE SOURCE FILE (NAME.CODE / NAME.hex, NAME.LISTING.TXT,
// NAME.SYMBOLS.TXT, NAME.DETAILS.TXT and a TOKENS*.TXT dump of the token table),
// so the microcode folder of this repository is regenerated by running the tool
// on each source in it (see eng\assemble-all.ps1).
//
// The sub-command names are a contract: other repositories (nd500uc, nd5000uc)
// call `nd500-disasm`, `nd500-asm`, `nd10-asm`, `nd10-disasm` and `nd5000-listing`
// by these names. Do not rename them.

if (args.Length == 0 || args[0] == "help" || args[0] == "--help" || args[0] == "-h")
{
    PrintUsage();
    return args.Length == 0 ? 1 : 0;
}

switch (args[0])
{
    // ------------------------------------------------------------ ND-110 / ND-120 (64-bit micro word)

    // nd110-asm <source.uc>: assemble ND-110 micro code (token table of the
    // ND-110/ND-120 Microprogrammer's Guide, ND-06.031.1 EN) to <source>.CODE.
    case "nd110-asm":
    {
        if (!ExpectArgs(2, "nd110-asm <source.uc>")) return 1;
        using Compiler asm = new Compiler();
        return asm.AssembleFile(args[1], isND120: false) != null ? 0 : 1;
    }

    // nd120-asm <source.uc> [K|L]: assemble ND-120 micro code. Version K is the
    // token table as printed; version L applies the post-load fixup where the
    // B,P / B,B / B,X register-select tokens lose the DLY1 delay bit
    // (ND120Tokens.AdjustTokensForVersionL). Default is K.
    case "nd120-asm":
    {
        if (args.Length != 2 && args.Length != 3)
        {
            Console.WriteLine("Usage: nd120-asm <source.uc> [K|L]");
            return 1;
        }
        string version = args.Length == 3 ? args[2].ToUpperInvariant() : "K";
        if (version != "K" && version != "L")
        {
            Console.WriteLine($"Unknown ND-120 micro code version '{args[2]}' - expected K or L");
            return 1;
        }
        using Compiler asm = new Compiler();
        return asm.AssembleFile(args[1], isND120: true, microcodeVersion: version) != null ? 0 : 1;
    }

    // ------------------------------------------------------------ NORD-10 (32-bit micro word)

    // nd10-asm <source.uc>: assemble NORD-10 MICMAC source to a ROM image
    // (<source>.hex in the prom.hex format and <source>.CODE binary).
    case "nd10-asm":
    {
        if (!ExpectArgs(2, "nd10-asm <source.uc>")) return 1;
        var nd10asm = new ND10Compiler();
        return nd10asm.AssembleFile(args[1]) != null ? 0 : 1;
    }

    // nd10-disasm <prom.hex> <out.uc>: lossless NORD-10 disassembly of a ROM dump
    // (one 32-bit hexadecimal word per line, the prom.hex format) to MICMAC
    // source: 'addr: mnemonics' per word. Reassembling with nd10-asm reproduces
    // the dump word for word.
    case "nd10-disasm":
    {
        if (!ExpectArgs(3, "nd10-disasm <prom.hex> <output.uc>")) return 1;
        uint[] rom = ND10Compiler.ReadHexFile(args[1]);
        var nd10dis = new ND10Disassembler();
        var src = new StringBuilder();
        src.AppendLine($"% {Path.GetFileName(args[1])} - generated by ND10Disassembler (lossless round-trip source)");
        for (int addr = 0; addr < rom.Length; addr++)
        {
            src.Append(ND10Compiler.Oct(addr)).Append(": ");
            src.AppendLine(nd10dis.DisassembleToString(rom[addr]));
        }
        File.WriteAllText(args[2], src.ToString());
        Console.WriteLine($"Disassembled {rom.Length} words from {args[1]} to {args[2]}");
        return 0;
    }

    // ------------------------------------------------------------ ND-500 (144-bit micro word, PACKED18)

    // nd500-asm <source.uc>: assemble ND-500 micro code source to a full 8K
    // PACKED18 control store image (<source>.CODE next to the source file).
    // StampDate stays on: word 0 bits 15-0 only get the date when the source
    // leaves them zero, so round-trip sources are unaffected.
    case "nd500-asm":
    {
        if (!ExpectArgs(2, "nd500-asm <source.uc>")) return 1;
        using ND500Compiler nd500asm = new ND500Compiler();
        return nd500asm.AssembleFile(args[1]) != null ? 0 : 1;
    }

    // nd500-disasm <DATA> <out.uc>: lossless ND-500 disassembly of a PACKED18
    // control store image to assembler source (one 'addr/ tokens ;' line per
    // word; values without an Appendix A mnemonic come out as FIELD=<octal>).
    // Reassembling the output with nd500-asm reproduces the image byte for byte.
    case "nd500-disasm":
    {
        if (!ExpectArgs(3, "nd500-disasm <controlstore.DATA> <output.uc>")) return 1;
        byte[] image = File.ReadAllBytes(args[1]);
        const int WORD_BYTES = ND500Compiler.WORD_PARTS * 2;
        if (image.Length % WORD_BYTES != 0)
        {
            Console.WriteLine($"Not a PACKED18 image: {image.Length} bytes is not a multiple of {WORD_BYTES}");
            return 1;
        }
        var disasm = new ND500Disassembler();
        var src = new StringBuilder();
        src.AppendLine($"% {Path.GetFileName(args[1])} - generated by ND500Disassembler (lossless round-trip source)");
        ushort[] word = new ushort[ND500Compiler.WORD_PARTS];
        int words = image.Length / WORD_BYTES;
        for (int addr = 0; addr < words; addr++)
        {
            int off = addr * WORD_BYTES;
            for (int i = 0; i < ND500Compiler.WORD_PARTS; i++)
            {
                word[i] = (ushort)((image[off + i * 2] << 8) | image[off + i * 2 + 1]);
            }
            List<string> tokens = disasm.Disassemble(word);
            if (tokens.Count == 0) continue;   // all-zero word: store stays zero
            AppendSourceLine(src, addr, tokens);
        }
        File.WriteAllText(args[2], src.ToString());
        Console.WriteLine($"Disassembled {words} words from {args[1]} to {args[2]}");
        return 0;
    }

    // ------------------------------------------------------------ ND-5000 (128-bit micro word, .DATA)

    // nd5000-asm <source.uc>: assemble ND-5000 micro code source to a full 16K
    // control store image in the original .DATA format (16 bytes per word,
    // big-endian; <source>.CODE next to the source file).
    case "nd5000-asm":
    {
        if (!ExpectArgs(2, "nd5000-asm <source.uc>")) return 1;
        using ND5000Compiler nd5000asm = new ND5000Compiler();
        return nd5000asm.AssembleFile(args[1]) != null ? 0 : 1;
    }

    // nd5000-disasm <DATA> <out.uc>: lossless ND-5000 disassembly of a .DATA
    // control store image to assembler source, one 'addr/ tokens ;' line per
    // non-zero word. Reassembling with nd5000-asm reproduces the image.
    case "nd5000-disasm":
    {
        if (!ExpectArgs(3, "nd5000-disasm <microcode.DATA> <output.uc>")) return 1;
        byte[] image = File.ReadAllBytes(args[1]);
        const int WORD_BYTES = ND5000Compiler.WORD_PARTS * 2;
        if (image.Length % WORD_BYTES != 0)
        {
            Console.WriteLine($"Not an ND-5000 .DATA image: {image.Length} bytes is not a multiple of {WORD_BYTES}");
            return 1;
        }
        var disasm = new ND5000Disassembler();
        var src = new StringBuilder();
        src.AppendLine($"% {Path.GetFileName(args[1])} - generated by ND5000Disassembler (lossless round-trip source)");
        ushort[] word = new ushort[ND5000Compiler.WORD_PARTS];
        int words = image.Length / WORD_BYTES;
        for (int addr = 0; addr < words; addr++)
        {
            ND5000Listing.GetWord(image, addr, word);
            List<string> tokens = disasm.Disassemble(word);
            if (tokens.Count == 0) continue;   // all-zero word: store stays zero
            AppendSourceLine(src, addr, tokens);
        }
        File.WriteAllText(args[2], src.ToString());
        Console.WriteLine($"Disassembled {words} words from {args[1]} to {args[2]}");
        return 0;
    }

    // nd5000-listing <DATA> <LABE> <out.md>: a lossless, line-validated ND-5000
    // micro code markdown listing in the exact format of the nd5000uc web
    // disassembler's markdown export - see ND5000Listing.cs.
    case "nd5000-listing":
    {
        if (!ExpectArgs(4, "nd5000-listing <microcode.DATA> <labels.LABE> <output.md>")) return 1;
        var listing = new ND5000Listing();
        listing.GenerateListingFile(args[1], args[2], args[3]);
        return 0;
    }

    default:
        Console.WriteLine($"Unknown command '{args[0]}'");
        Console.WriteLine();
        PrintUsage();
        return 1;
}

// Exact argument count check shared by the fixed-arity sub-commands.
bool ExpectArgs(int count, string usage)
{
    if (args.Length == count) return true;
    Console.WriteLine("Usage: " + usage);
    return false;
}

// One 'addr/ token token ... ;' source line, the form the ND-500 and ND-5000
// assemblers read back. Address is six octal digits.
static void AppendSourceLine(StringBuilder src, int addr, List<string> tokens)
{
    src.Append(Convert.ToString(addr, 8).PadLeft(6, '0')).Append("/ ");
    for (int i = 0; i < tokens.Count; i++)
    {
        if (i > 0) src.Append(' ');
        src.Append(tokens[i]);
    }
    src.AppendLine(" ;");
}

static void PrintUsage()
{
    Console.WriteLine("ndmicroasm - Norsk Data micro code assemblers and disassemblers");
    Console.WriteLine("Copyright (c) 1985-" + DateTime.Now.Year + " Ronny Hansen, RetroCore Labs, MIT license");
    Console.WriteLine();
    Console.WriteLine("Usage: ndmicroasm <command> <arguments>");
    Console.WriteLine();
    Console.WriteLine("  NORD-10 (32-bit micro word, MICMAC mnemonics of ND-06.010.01)");
    Console.WriteLine("    nd10-asm      <source.uc>                      -> <source>.hex, <source>.CODE, listing, symbols");
    Console.WriteLine("    nd10-disasm   <prom.hex> <output.uc>            lossless disassembly of a PROM dump");
    Console.WriteLine();
    Console.WriteLine("  ND-110 and ND-120 (64-bit micro word, ND-06.031.1 EN)");
    Console.WriteLine("    nd110-asm     <source.uc>                      -> <source>.CODE, listing, symbols, details");
    Console.WriteLine("    nd120-asm     <source.uc> [K|L]                 same, ND-120 token table; L = version-L fixup (default K)");
    Console.WriteLine();
    Console.WriteLine("  ND-500 (144-bit micro word, PACKED18 image, ND-30.013.02 Appendix A)");
    Console.WriteLine("    nd500-asm     <source.uc>                      -> <source>.CODE (8K words x 18 bytes)");
    Console.WriteLine("    nd500-disasm  <controlstore.DATA> <output.uc>   lossless disassembly");
    Console.WriteLine();
    Console.WriteLine("  ND-5000 (128-bit micro word, .DATA image)");
    Console.WriteLine("    nd5000-asm    <source.uc>                      -> <source>.CODE (16K words x 16 bytes)");
    Console.WriteLine("    nd5000-disasm <microcode.DATA> <output.uc>      lossless disassembly");
    Console.WriteLine("    nd5000-listing <microcode.DATA> <labels.LABE> <output.md>   markdown listing (nd5000uc format)");
    Console.WriteLine();
    Console.WriteLine("Every assembler writes its outputs next to the source file. Exit code 0 = success, 1 = error.");
}
