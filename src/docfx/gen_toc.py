#!/usr/bin/env python3
"""Writes src/docs/toc.yml: the Guides section of the documentation site.

One command regenerates the list, from the files git tracks (an untracked note must never reach the
site's navigation, or the clean checkout that CI builds has a link to a file it does not have):

    python src/docfx/gen_toc.py            write src/docs/toc.yml
    python src/docfx/gen_toc.py --check    exit 1 when the file on disk is not what this script writes (CI runs this)

What is a guide (the policy). The content group in docfx.json uses the same three globs, so every
page DocFX builds is in the tree and nothing in the tree is missing from the build:

  ON   every .md file in src/docs/
  ON   the README.md of every folder under src/NDMicroAsm/microcode/ (the reference dumps describe themselves)
  ON   src/CHANGELOG.md, last
  OFF  the repository front page README.md (the site's home page is src/docfx/index.md),
       .github/ (CONTRIBUTING and SECURITY are for GitHub), src/docfx/README.md (how to build the site)

Each entry is named after the document's first-level heading, never typed here.

The API reference is not listed here: DocFX writes it from the XML comments of the project.
"""
import os
import subprocess
import sys

REPO = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
OUT = os.path.join(REPO, "src", "docs", "toc.yml")


def tracked():
    out = subprocess.check_output(["git", "-C", REPO, "ls-files", "src"], text=True)
    return sorted(out.splitlines())


def title(path):
    with open(os.path.join(REPO, path), encoding="utf-8") as f:
        for line in f:
            if line.startswith("# "):
                return line[2:].strip()
    raise SystemExit(path + " has no first-level heading to name it by")


def build():
    files = tracked()
    guides = [f for f in files if f.startswith("src/docs/") and f.endswith(".md")]
    dumps = [f for f in files if f.startswith("src/NDMicroAsm/microcode/") and f.endswith("/README.md")]
    pages = guides + dumps
    if "src/CHANGELOG.md" in files:
        pages.append("src/CHANGELOG.md")

    lines = [
        "# Generated by src/docfx/gen_toc.py from the files git tracks. Edit the script or the documents, then run it again.",
    ]
    for page in pages:
        lines.append("- name: " + title(page))
        # toc.yml sits in src/docs/, so every link is written from there
        lines.append("  href: " + os.path.relpath(page, "src/docs").replace(os.sep, "/"))
    return "\n".join(lines) + "\n"


def main():
    wanted = build()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current.replace("\r\n", "\n") != wanted:
            print("src/docs/toc.yml is out of date: run  python src/docfx/gen_toc.py  and commit the result.")
            return 1
        print("src/docs/toc.yml is current.")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(wanted)
    print("wrote", os.path.relpath(OUT, REPO), "-", wanted.count("\n"), "lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
