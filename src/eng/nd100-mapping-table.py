#!/usr/bin/env python3
"""Writes microcode/ND-100/ND-100-MAPPING.md from the mapping PROM chips.

The mapping PROM (the decode PLA of the chip archive) of the ND-100 turns a machine
instruction into the micro address where its micro program starts. This script reads the
six chip files in microcode/ND-100/REFERENCE/DECODE/, joins the three chips of each card
into a table of 2048 entries of 12 bits, names every entry with the labels of the
reconstructed sources, and checks the table against the sources and against the ND-110
micro code. The numbers in the document are computed here, not typed.

Run from anywhere:  python3 src/eng/nd100-mapping-table.py
"""
import itertools
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'NDMicroAsm', 'microcode'))
ND100 = os.path.join(ROOT, 'ND-100')
DEC = os.path.join(ND100, 'REFERENCE', 'DECODE')
OUT = os.path.join(ND100, 'ND-100-MAPPING.md')

CARDS = {
    '3033S': ['01600N.82s185.b20', '01601N.82s185.b19', '01602N.82s185.b18'],
    '3033E-CX': ['08600D.82s185.b20', '08601D.82s185.b19', '08602D.82s185.b18'],
}


def chips(card):
    return [open(os.path.join(DEC, card, n), 'rb').read() for n in CARDS[card]]


def table(card, order=(0, 1, 2), invert=False):
    ch = chips(card)
    out = []
    for i in range(2048):
        n = [ch[p][i] & 15 for p in order]
        v = n[0] | (n[1] << 4) | (n[2] << 8)
        out.append(v ^ 0xFFF if invert else v)
    return out


def symbols(path):
    d = {}
    for line in open(path, errors='replace'):
        m = re.match(r'^(\d{6})=(\S+)', line)
        if m:
            d.setdefault(int(m.group(1), 8), m.group(2))
    return d


def o(v, w=4):
    return format(v, 'o').zfill(w)


S = table('3033S')
C = table('3033E-CX')
LS = symbols(os.path.join(ND100, 'ND-100-3033S.SYMBOLS.TXT'))
LC = symbols(os.path.join(ND100, 'ND-100-3033E-CX.SYMBOLS.TXT'))
L110 = symbols(os.path.join(ROOT, 'ND-110', 'ND-110-RASK.SYMBOLS.TXT'))


def name(t, labels):
    if t in labels:
        return labels[t]
    if 0o7377 <= t <= 0o7413:
        return '(WCS area, not in ROM)'
    return '?'


# Checks ---------------------------------------------------------------------------------
labels_s = set(LS)
order_hits = []
for order in itertools.permutations(range(3)):
    for inv in (False, True):
        t = table('3033S', order, inv)
        order_hits.append((sum(1 for v in t if v in labels_s), order, inv))
order_hits.sort(reverse=True)
best = order_hits[0]
second = order_hits[1]

off_s = sorted({t for t in S if t not in LS})
off_c = sorted({t for t in C if t not in LC})
n_off_s = sum(1 for t in S if t not in LS)
n_off_c = sum(1 for t in C if t not in LC)

half_diff = [i for i in range(1024) if S[i] != S[i + 1024]]
priv_names = sorted({name(S[i + 1024], LS) for i in half_diff if S[i] == 0o30})
only_priv = sum(1 for i in half_diff if S[i] == 0o30)

same = []
diff = []
for k in range(1024):
    n110 = L110.get(0o6000 + k)
    if not n110:
        continue
    n100 = LS.get(S[k + 1024])
    if n100 is None:
        continue
    (same if n100 == n110 else diff).append((k, n110, n100))

cx_diff = [i for i in range(2048) if S[i] != C[i]]


def runs(t, labels, upper):
    base = 1024 if upper else 0
    rows = []
    k = 0
    while k < 1024:
        j = k
        while j + 1 < 1024 and t[base + j + 1] == t[base + k]:
            j += 1
        rows.append((k, j, t[base + k]))
        k = j + 1
    return rows


def merged_rows():
    """Runs of the upper half (ring 2-3), with the ring 0-1 target where it differs."""
    rows = []
    k = 0
    while k < 1024:
        j = k
        key = (S[1024 + k], S[k])
        while j + 1 < 1024 and (S[1024 + j + 1], S[j + 1]) == key:
            j += 1
        rows.append((k, j, S[1024 + k], S[k]))
        k = j + 1
    return rows


w = []
add = w.append
add('# ND-100 mapping PROM: machine instruction to micro address')
add('')
add('<!-- generated by src/eng/nd100-mapping-table.py; edit the script and run it again -->')
add('')
add('## In short')
add('')
add('- The ND-100 has a PROM that tells the micro program where to start for each machine instruction.')
add('  The ND-100 manual calls it the **mapping PROM**; the chip archive calls it the **decode PLA**.')
add('- It has **2048 entries of 12 bits** (three 82S185 chips of 2K x 4). The 12 bits are a micro address.')
add('- The address inputs are **bits 15 to 6 of the machine instruction (IR >> 6)** and **one more line,')
add('  the ring state**. With ring 0-1 (restricted mode) the privileged instructions go to `PRIVI`;')
add('  with ring 2-3 they go to their real routines.')
add('- The microcode source has no table for it. The table below is read from the chips and checked against')
add('  the labels of `ND-100-3033S.uc` and `ND-100-3033E-CX.uc`.')
add('')
add('## How the hardware uses it (to build an ND-100 micro code CPU)')
add('')
add('What the files say (manual ND-06.018.01 and the printed micro code listing):')
add('')
add('1. A micro instruction with **bit 27 (MAPJ, written `T,MAPJ`)** loads IR from the IDB. The manual: bit 27')
add('   "is active low, and will load IR from IDB in the next instruction. It will clear the R = P flip-flop.')
add('   It sets the false sequence control to JUMP and POP ..." In the source it is on `FTCH2` (0o%s):' % o(min(a for a, n in LS.items() if n == 'FTCH2'), 2))
add('   `PIC,RVECT ALUD,NONE / IDBS,GPR T,MAPJ T,JMP T,HOLD / FETCH;`')
add('2. The next micro instruction is a **jump (`T,JMP`) whose address field is 0**. This is `FETCH` (0o%s),' % o(min(a for a, n in LS.items() if n == 'FETCH'), 2))
add('   labelled in the print "MAPPING POINT FOR ALL INSTRUCTIONS. NEXT MICROADDRESS IS TAKEN FROM MAPPING PROM,')
add('   OR CONTROLLED BY THE INTERRUPT HARDWARE (INTERRUPT VECTOR)". The manual: "If the next microinstruction')
add('   is a JMP, the address will be taken from the mapping PROM, or be generated by the interrupt hardware if')
add('   CLIRQ command has not been given." And for bits 0-11: when the PROM or the interrupt hardware makes the')
add('   address, "the corresponding microword bits must be 0".')
add('3. So the next-address multiplexer of the sequencer has three sources for the 12-bit jump address:')
add('   the micro word (bits 0-11), the mapping PROM output, and the interrupt vector from the interrupt')
add('   hardware. At the mapping point the PROM output is used unless an interrupt is pending and')
add('   `COMM,CLIRQ` was not given; then the interrupt vector is used.')
add('4. The PROM address is `{ring, IR[15:6]}`: 11 lines. Entry `(ring << 10) | (IR >> 6)` is the micro address')
add('   to jump to. Every machine instruction in the same group of 64 (IR bits 5-0 differ) gets the same entry;')
add('   the micro program separates them itself (for example with `T,JMP0-3`, `T,JMP8-10` and `A,REG`).')
add('5. `PRIVI` (0o30) is "CODE FOR PRIVILEGED INSTRUCTION IF ON RING 0-1" and `ILLIN` (0o27) is "CODE FOR')
add('   ILLEGAL INTRUCTION" (spelling as printed). `COND,RESTR` is the micro condition that tests the same')
add('   ring state ("running in restricted mode ... Instructions that are privileged should not execute when this')
add('   condition is true").')
add('')
add('What is proved by the chips, and what is not:')
add('')
add('| Statement | Status |')
add('|---|---|')
add('| 12-bit entries, chip b20 = bits 3-0, b19 = bits 7-4, b18 = bits 11-8 | proved: see Checks |')
add('| Index = IR bits 15-6 | proved: 32 entries per memory reference instruction, in the instruction order |')
add('| The 11th line selects between PRIVI and the real routine for privileged instructions | proved by the table; that it is the ring state follows from the labels and `COND,RESTR` |')
add('| Which physical signal drives the 11th line, and in which micro cycle IR is latched and the PROM read | **unknown**: needs the 3033 card schematics, which are not in our files |')
add('| How an entry 0o7401 becomes micro address 0o4001 (see the WCS area below) | **unknown** |')
add('')
add('## The chips')
add('')
add('| Card | Chips (82S185, 2K x 4) | Folder |')
add('|---|---|---|')
add('| 3033S | `01600N` (b20), `01601N` (b19), `01602N` (b18) | `microcode/ND-100/REFERENCE/DECODE/3033S/` |')
add('| 3033E-CX | `08600D` (b20), `08601D` (b19), `08602D` (b18) | `microcode/ND-100/REFERENCE/DECODE/3033E-CX/` |')
add('')
add('Entry `i` = `(b20[i] & 15) | ((b19[i] & 15) << 4) | ((b18[i] & 15) << 8)`.')
add('')
add('## Checks')
add('')
add('- **Chip order.** All 6 orders of the 3 chips, with and without inverting the 12 bits, were tried on the')
add('  3033S. The number of the 2048 entries that land exactly on a label of `ND-100-3033S.uc`:')
add('  best order (b20, b19, b18; not inverted) %d; the next best %d. So the order is right.' % (best[0], second[0]))
add('- **Targets.** 3033S: %d of 2048 entries point to a label of the source; the other %d point to the WCS area' % (2048 - n_off_s, n_off_s))
add('  (%s). 3033E-CX: %d of 2048 on a label, %d in the WCS area (%s).' % (
    ' '.join(o(x) for x in off_s), 2048 - n_off_c, n_off_c, ' '.join(o(x) for x in off_c)) + '.')
add('- **Privilege line.** The lower half (ring 0-1) and the upper half (ring 2-3) of the 3033S table differ in %d of 1024' % len(half_diff))
add('  entries. In %d of them the lower half is `PRIVI`, and the upper half is one of: %s.' % (only_priv, ', '.join(priv_names)))
add('  These are the privileged instructions (and the opcodes that are illegal on ring 2-3 but trap as')
add('  privileged on ring 0-1).')
add('- **ND-110.** The ND-110 micro code has its table inside the control store: the word at')
add('  `0o6000 + (IR >> 6)` is the first micro instruction of the machine instruction (0o6000 to 0o7777, 1024')
add('  words, from `MICRO-RASK-ENTRY`). It has the same layout as the upper half of this PROM: `STZ` at')
add('  0o6000, `STA` at 0o6040, `STT` at 0o6100 and so on, 32 entries apart, then the same order as the ND-100')
add('  runs below. (The shift is 6, not 3: with `IR >> 3` `STA` would be at 0o6400, which holds `MIN`.)')
add('  Of the %d entries where both the ND-110 and the ND-100 name the same index with a label, %d have the' % (len(same) + len(diff), len(same)))
add('  same name. The other %d differ only in spelling, except `IOT`:' % len(diff))
add('')
add('  | IR >> 6 | ND-110 label | ND-100 label |')
add('  |---|---|---|')
for k, a, b in diff:
    add('  | %s | `%s` | `%s` |' % (o(k), a, b))
add('')
add('  `IOT` is an ND-110 instruction at IR 0o1600xx; the ND-100 treats it as illegal (`ILLIN`).')
add('')
add('## The table (3033S)')
add('')
add('One row for each run of equal entries. "IR range" is the machine instruction word, octal. "Ring 2-3" is')
add('the entry with the ring line high; "Ring 0-1" is shown only where it differs. Names are the labels of')
add('`ND-100-3033S.uc` at the entry address.')
add('')
add('| IR range | Index | Ring 2-3 entry | Label | Ring 0-1 |')
add('|---|---|---|---|---|')
for a, b, t_hi, t_lo in merged_rows():
    lo = ''
    if t_lo != t_hi:
        lo = '%s `%s`' % (o(t_lo), name(t_lo, LS))
    add('| %s - %s | %s%s | %s | `%s` | %s |' % (
        o(a << 6, 6), o((b << 6) | 0o77, 6), o(a), '' if a == b else ' - ' + o(b), o(t_hi), name(t_hi, LS), lo))
add('')
add('### The WCS area')
add('')
add('The entries 0o7400 to 0o7413 (and 0o7377) are not in the ROM. The manual says bit 26 (`SLWCS`) must be')
add('followed by "a jump to microaddress 7400" to load the WCS, and that the customer instructions have their')
add('entries in the WCS at 4001 to 4015; before `LWCS` has run they cause the ROM-out-of-range interrupt.')
add('The PROM holds 0o7400 + n for the customer instruction codes; how that becomes 0o4001 + n is not in our files.')
add('')
add('## 3033E-CX: where it differs from the 3033S')
add('')
add('%d entries differ (index = ring line and IR >> 6, octal):' % len(cx_diff))
add('')
add('| Index | 3033S | 3033E-CX | ND-110 label at that index |')
add('|---|---|---|---|')
for i in cx_diff:
    k = i & 1023
    add('| %s | %s `%s` | %s `%s` | %s |' % (o(i), o(S[i]), name(S[i], LS), o(C[i]), name(C[i], LC), L110.get(0o6000 + k, '')))
add('')
add('On the 3033E-CX the instructions `S3SEG` (IR 0o1403xx), `GECO` (0o1427xx) and `MOVEW` (0o1431xx) are')
add('implemented in the CX option bank (entries 0o6350, 0o6325 and 0o6477), where the 3033S points them into')
add('the WCS area. The ND-110 names the same three indexes `S3SEG`, `GECO` and `MOVEW`. `COMME` is a name in both')
add('banks; the CX source writes the extension bank copy `COMME_CX`.')
add('')
open(OUT, 'w', newline='\n').write('\n'.join(w) + '\n')
print('wrote', os.path.relpath(OUT, ROOT), len(w), 'lines')
print('best order hits', best, 'next', second[0], '| off-label 3033S', n_off_s, '3033E-CX', n_off_c, '| half diff', len(half_diff),
      '| ND-110 same', len(same), 'different', len(diff), '| CX diffs', len(cx_diff))
