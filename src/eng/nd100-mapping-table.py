#!/usr/bin/env python3
"""Writes microcode/ND-100/ND-100-MAPPING.md from the decode (mapping) PROM dumps.

Input (all inside this repository, paths derived from this file):
  src/NDMicroAsm/microcode/ND-100/REFERENCE/DECODE/3033S/       three 82S185 dumps (b20 b19 b18)
  src/NDMicroAsm/microcode/ND-100/REFERENCE/DECODE/3033E-CX/    three 82S185 dumps (b20 b19 b18)
  src/NDMicroAsm/microcode/ND-100/*.SYMBOLS.TXT                 labels of the assembled ND-100 sources
  src/NDMicroAsm/microcode/ND-110/ND-110-RASK.SYMBOLS.TXT       labels of the ND-110 source (cross check)

The script stops with an error if a check fails. Run from anywhere: python3 src/eng/nd100-mapping-table.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MC = os.path.join(HERE, "..", "NDMicroAsm", "microcode")
ND100 = os.path.join(MC, "ND-100")

CARDS = [
    ("3033S", "3033S", ["01600N.82s185.b20", "01601N.82s185.b19", "01602N.82s185.b18"], "ND-100-3033S.SYMBOLS.TXT"),
    ("3033E-CX", "3033E-CX", ["08600D.82s185.b20", "08601D.82s185.b19", "08602D.82s185.b18"], "ND-100-3033E-CX.SYMBOLS.TXT"),
]


def load_table(folder, files):
    chips = [open(os.path.join(ND100, "REFERENCE", "DECODE", folder, f), "rb").read() for f in files]
    for c in chips:
        if len(c) != 2048:
            sys.exit("chip is not 2048 bytes")
    # Each 82S185 byte holds the 4 bits in its low nibble. b20 = bits 3-0, b19 = bits 7-4, b18 = bits 11-8.
    return [(chips[0][i] & 15) | ((chips[1][i] & 15) << 4) | ((chips[2][i] & 15) << 8) for i in range(2048)]


def load_symbols(path):
    d = {}
    for line in open(path, errors="replace"):
        m = re.match(r"^(\d{6})=(\S+)", line)
        if m:
            d.setdefault(int(m.group(1), 8), m.group(2))
    return d


def runs(table, lo, hi):
    """Runs of equal entries in table[lo:hi]: list of (first index, last index, entry)."""
    out = []
    start = lo
    for i in range(lo + 1, hi + 1):
        if i == hi or table[i] != table[start]:
            out.append((start, i - 1, table[start]))
            start = i
    return out


def ir_range(i0, i1):
    return "%06o-%06o" % (i0 << 6, ((i1 + 1) << 6) - 1)


def main():
    l110 = load_symbols(os.path.join(MC, "ND-110", "ND-110-RASK.SYMBOLS.TXT"))
    tables, labels = {}, {}
    for name, folder, files, sym in CARDS:
        tables[name] = load_table(folder, files)
        labels[name] = load_symbols(os.path.join(ND100, sym))

    out = []
    w = out.append
    w("# ND-100 mapping PROM (decode PLA)\n")
    w("<!-- generated by src/eng/nd100-mapping-table.py from the chip dumps in REFERENCE/DECODE; do not edit by hand -->\n")
    w("What the three 82S185 PROMs in slots b18, b19 and b20 of the ND-100 CPU card hold, how the hardware uses them, and how this was checked.\n")

    w("## How the hardware uses it\n")
    w("**Facts read from the files** (the manual text is in `ND100-MICROCODE_combined.md`, bit 27 and bits 0-11 of the microword; the rest from the chip dumps and the assembled sources):\n")
    w("1. The microcode does a *mapped jump* when a microinstruction has `T,MAPJ` and the next microinstruction is a jump (`T,JMP`). "
      "The jump address is then not taken from bits 0-11 of that microword (they must be 0) but from the mapping PROM. "
      "The interrupt hardware can replace it with an interrupt vector, unless `COMM,CLIRQ` was given. "
      "The label `FETCH` (0o16, banner `MAPPING POINT FOR ALL INSTRUCTIONS`) is the place where this happens for every machine instruction.\n")
    w("2. The PROM is 2048 words of 12 bits (three 82S185, each 2K x 4). Chip b20 holds bits 3-0 of the entry, b19 bits 7-4, b18 bits 11-8. "
      "The entry is a microcode address (12 bits, the same width as the branch address of the microword). "
      "This reading puts 2022 of the 3033S entries exactly on a label of the assembled source; the other five chip orders and the inverted forms give at most 1136.\n")
    w("3. The address of the PROM is **IR bits 15-6** (10 lines: opcode, addressing mode bits and the top two displacement bits of the machine instruction in the instruction register) "
      "plus **one more line** (index bit 10, value 0o2000). Evidence for the 10 bits: every memory reference opcode owns a run of exactly 32 entries "
      "(`STZ` 0o0000-0o0037, `STA` 0o0040-0o0077, `STT`, `STX`, `STD`, `LDD`, `STF`, `LDF`, `MIN`, `LDA`, ..., 32 x opcode number), "
      "and the manual names `1403xx` as `CUST2`, which is index 0o1403. The low 6 bits of the instruction are not used by the PROM: the microcode "
      "decodes them itself with the vectored jumps (`T,JMP0-3`, `T,JMP8-10`, `T,JMPALD`, `T,JMPAOPR`, `A,REG`).\n")
    w("4. The two halves of the PROM (index bit 10 = 0 and = 1) are equal except for 84 of 1024 entries. In every one of them the lower half "
      "(bit 10 = 0) has the entry of the label `PRIVI` and the upper half (bit 10 = 1) the real routine "
      "(`IDENT`, `LDWCS`, `TRA`, `TRR`, `MCL`, `MST`, `PIONF`, `WAIT`, `SRB`, `LRB`, `IRW`, `IRR`, `IOX`, `SINTR`) or `ILLIN` for opcodes that do not exist. "
      "So index bit 10 is a *privileged instructions allowed* line: 0 gives the privileged instruction trap, 1 lets the instruction run.\n")
    w("**Inferred, not proved by the files** (the schematics of the 3033 card would settle it): which signal drives index bit 10. "
      "The manual has `COND,RESTR` (\"restricted mode, true if ring 0-1\"); the behaviour above fits the line being *not restricted* (ring 2-3). "
      "Also not explained by the files: customer instruction entries (index 0o1402-0o1427 for opcodes 1402xx-1427xx) hold 0o7400-0o7413 on the 3033S, "
      "but the manual says execution goes to the writable control store at 0o4001-0o4015 after `LWCS` (`1403xx` = `CUST2` = 0o4001, and the PROM holds 0o7401). "
      "The difference is the bits 0o3400 of the 12 bit address; the logic that turns one into the other (the ROM-out-of-range test of the manual) is not in our files.\n")
    w("**To build an ND-100 microcode CPU from this** (what a model needs):\n")
    w("```\n"
      "at the microinstruction with T,MAPJ followed by T,JMP:\n"
      "    index   = (IR >> 6) & 0x3FF                 ; IR bits 15-6\n"
      "    if not restricted_mode: index |= 0x400      ; index bit 10 (inferred line, see above)\n"
      "    next_uaddr = MAP[index]                     ; 12 bit entry from the 2048 word table below\n"
      "unless an interrupt is pending and COMM,CLIRQ was not given: then the interrupt hardware supplies the address\n"
      "```\n")
    w("The table can be rebuilt from the six chip files in `REFERENCE/DECODE/`; the runs below are the same data in readable form.\n")

    w("## Checks\n")
    for name, _, _, _ in CARDS:
        t, lab = tables[name], labels[name]
        off = sorted({e for e in t if e not in lab})
        n_off = sum(1 for e in t if e not in lab)
        if any(e < 0o7377 for e in off):
            sys.exit("an entry points at an address that is neither a label nor in the 0o7377-0o7413 range")
        w("- **%s**: %d of 2048 entries are the address of a label of the assembled source. The other %d entries (addresses %s) are in the "
          "writable control store range, where the printed ROM listing has no code (the customer instruction entries 0o7400-0o7413 and, on the 3033S, 0o7377 for index 0o1431, which the 3033E-CX maps to `MOVEW`)."
          % (name, 2048 - n_off, n_off, " ".join("0o%o" % e for e in off)))
    t = tables["3033S"]
    ok = bad = 0
    bad_list = []
    for k in range(1024):
        n110 = l110.get(0o6000 + k)
        n100 = labels["3033S"].get(t[k + 1024])
        if not n110 or not n100:
            continue
        if n110 == n100:
            ok += 1
        else:
            bad += 1
            bad_list.append("%04o %s/%s" % (k, n110, n100))
    w("- **ND-110 cross check**: the ND-110 microcode (`ND-110-RASK.uc`) has the first microinstruction of each machine instruction at `0o6000 + index`, with the instruction names as labels "
      "(`STZ` at 0o6000, `STA` at 0o6040, `FAD` at 0o7000, `JUMP` at 0o7240 ...). The same index in the 3033S PROM (bit 10 = 1) points at a label of the same name in %d cases and at a spelling variant "
      "or another name in %d cases. The variants are the same instruction (ND-110 / ND-100 label): %s. "
      "The ND-110 table also shows that the index is IR bits 15-6 (`IR >> 6`), not `IR >> 3`: the manual gives `LWCS` as 143500 and `CUST2` as 1403xx, and the ND-110 has the labels `WCS` at 0o6000 + 0o1435 and `S3SEG` at 0o6000 + 0o1403 (the 3033E-CX card maps 1403xx to `S3SEG`), "
      "while `143500 >> 3` would be 0o14350 and has no entry in the table."
      % (ok, bad, ", ".join(bad_list)))
    s, c = tables["3033S"], tables["3033E-CX"]
    diffs = [i for i in range(2048) if s[i] != c[i]]
    w("- **3033S against 3033E-CX**: %d of 2048 entries differ. The 3033E-CX card maps `COMME` (index 0o1401), `S3SEG` (0o1403), `GECO` (0o1427) and `MOVEW` (0o1431) "
      "to routines in its extension bank (0o4037, 0o6350, 0o6325, 0o6477) where the 3033S card has the `PRIVI` trap or a writable control store address. "
      "The ND-110 table has the same four names at the same indices (`COMM`, `S3SEG`, `GECO`, `MOVEW`)." % len(diffs))
    w("")

    for name, _, _, _ in CARDS:
        t, lab = tables[name], labels[name]
        w("## Table: %s card, privileged instructions allowed (index bit 10 = 1)\n" % name)
        w("Index is the lower 10 bits (add 0o2000 for the full 11 bit address). `IR` is the range of machine instruction words that map to the run.\n")
        w("| Index (10 bit) | IR | Entry | Label | Notes |")
        w("|---|---|---|---|---|")
        for a, b, e in runs(t, 1024, 2048):
            ia, ib = a - 1024, b - 1024
            label = lab.get(e, "")
            note = "" if label else "writable control store address, no ROM code"
            if t[ia] != t[ia + 0] or t[a - 1024] != e:
                pass
            w("| %04o-%04o | %s | %04o | %s | %s |" % (ia, ib, ir_range(ia, ib), e, label, note))
        w("")
        w("## Differences of the lower half (index bit 10 = 0) from the upper half, %s card\n" % name)
        w("| Index (10 bit) | IR | Entry bit 10 = 0 | Label | Entry bit 10 = 1 | Label |")
        w("|---|---|---|---|---|---|")
        i = 0
        while i < 1024:
            if t[i] == t[i + 1024]:
                i += 1
                continue
            j = i
            while j + 1 < 1024 and t[j + 1] != t[j + 1 + 1024] and t[j + 1] == t[i] and t[j + 1 + 1024] == t[i + 1024]:
                j += 1
            w("| %04o-%04o | %s | %04o | %s | %04o | %s |" % (i, j, ir_range(i, j), t[i], lab.get(t[i], ""), t[i + 1024], lab.get(t[i + 1024], "")))
            i = j + 1
        w("")

    open(os.path.join(ND100, "ND-100-MAPPING.md"), "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote ND-100-MAPPING.md;", "ND-110 same name %d, variants %d" % (ok, bad), "S vs CX diffs", len(diffs))


if __name__ == "__main__":
    main()
