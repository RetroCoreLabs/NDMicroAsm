#!/usr/bin/env python3
"""
Writes NDMicroAsm/ND1X0/ND100Tokens.cs from the ND-100 token definitions.

The token values are kept in one place: the file defs/tokens/nd100-tokens.yaml of the
nd-microcode-meta repository (https://github.com/RetroCoreLabs/nd-microcode-meta). This
script copies them into C#, so the table of the assembler is the table of the disassemblers.
Never edit ND100Tokens.cs by hand; change the YAML and run this script again.

Usage (from the src folder of this repository):

    python3 eng/gen-nd100-tokens.py --yaml <path to nd100-tokens.yaml>
    python3 eng/gen-nd100-tokens.py --yaml <path> --check     write nothing, exit 1 if the file would change

--yaml may be left out when the environment variable ND_MICROCODE_META names the folder
of the nd-microcode-meta checkout.

Compiler flags (Constants.*) come from the category of the token (A_REG -> IsA, B_REG -> IsB,
AB_REG -> IsA_B, PIC -> IsPIC, IDBS -> IsIDBS, COND -> IsCond, T_SEQ -> IsTrueAddr,
T_STK -> IsTrueStack, F_SEQ -> IsFalseAddr, F_STK -> IsFalseStack). No Require* flag is set:
the ND-110 rules ("this ALU function needs an A operand") are not written in the ND-100
manual, and the ND-100 PROMs leave A and B out in many words. The flags only control
warnings in Compiler.CheckCompilerWarnings; they never change the micro word.
"""

import argparse
import os
import sys

try:
    import yaml
except ImportError:
    sys.exit("PyYAML is needed: pip install pyyaml")

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(HERE)
OUT = os.path.join(SRC, "NDMicroAsm", "ND1X0", "ND100Tokens.cs")

IS_FLAGS = {
    "A_REG": "Constants.IsA",
    "B_REG": "Constants.IsB",
    "AB_REG": "Constants.IsA_B",
    "PIC": "Constants.IsPIC",
    "IDBS": "Constants.IsIDBS",
    "COND": "Constants.IsCond",
    "T_SEQ": "Constants.IsTrueAddr",
    "T_STK": "Constants.IsTrueStack",
    "F_SEQ": "Constants.IsFalseAddr",
    "F_STK": "Constants.IsFalseStack",
}

HEADER = """//
// SPDX-License-Identifier: MIT
// Copyright (c) 1985-2026 Ronny Hansen
// RetroCore Labs — https://github.com/RetroCoreLabs/NDMicroAsm
// NDMicroAsm — Assembling yesterday's micro code with today's tools
//

// <auto-generated>
//   Written by eng/gen-nd100-tokens.py from defs/tokens/nd100-tokens.yaml of
//   nd-microcode-meta. Do not edit by hand: change the YAML and run the script again.
//   Values checked against ND-06.018.01 "NORD-100 Microprogramming Description", Appendix A.
// </auto-generated>

namespace NDMicroAsm.ND1X0
{
    /// <summary>
    /// The mnemonics of the ND-100 micro word (ND-06.018.01 EN, NORD-100 Microprogramming
    /// Description). The values are the ones the programmer writes, with bits 22-27 active
    /// high; <see cref="Compiler"/> inverts bits 22-27 when it writes the word, as the manual
    /// says ("bits 22 - 27 are inverted after the word is assembled").
    /// </summary>
    internal class ND100Tokens : TokensBase
    {
        internal override void InitializeTokens()
        {
            Clear();
"""

FOOTER = """        }
    }
}
"""


def cs_string(text):
    return text.replace('"', '""')


def build(yaml_path):
    with open(yaml_path, encoding="utf-8") as f:
        data = yaml.safe_load(f)
    tokens = data["tokens"]
    out = [HEADER]
    for t in tokens:
        enc = t["encoding"]
        w = [str(enc[k]) for k in ("w4", "w3", "w2", "w1")]
        flags = []
        if t["category"] in IS_FLAGS:
            flags.append(IS_FLAGS[t["category"]])
        # a bare Is flag needs no cast; several flags are OR'ed into a ushort
        if len(flags) == 0:
            flag_text = ""
        elif len(flags) == 1:
            flag_text = ", " + flags[0]
        else:
            flag_text = ", (ushort)(" + " | ".join(flags) + ")"
        desc = cs_string(str(t.get("description", "")).strip())
        out.append(
            '            AddToken("%s", "%s", "%s", "%s", "%s", @"%s"%s);\n'
            % (t["token"], w[0], w[1], w[2], w[3], desc, flag_text)
        )
    out.append(FOOTER)
    return "".join(out), len(tokens)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--yaml", help="path of nd100-tokens.yaml")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    yaml_path = args.yaml
    if not yaml_path:
        meta = os.environ.get("ND_MICROCODE_META")
        if not meta:
            sys.exit("give --yaml <nd100-tokens.yaml> or set ND_MICROCODE_META")
        yaml_path = os.path.join(meta, "defs", "tokens", "nd100-tokens.yaml")
    text, count = build(yaml_path)
    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("ND100Tokens.cs is out of date; run eng/gen-nd100-tokens.py")
            sys.exit(1)
        print("ND100Tokens.cs is up to date (%d tokens)" % count)
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d tokens)" % (OUT, count))


if __name__ == "__main__":
    main()
